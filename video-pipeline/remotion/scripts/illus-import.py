#!/usr/bin/env python3
"""Put the traced illustrations into the art library.

Reads `library/illus/manifest.json` (name, about, tags, search per drawing) and the traced SVGs beside it
(`library/illus/<name>.svg`, from scripts/illus-trace.py), and writes `src/paper/illus.ts`: one entry per
drawing with its stroke paths, so `Art` can draw it stroke by stroke like any catalogue drawing, the hand following.

    python3 scripts/illus-import.py
"""
from __future__ import annotations

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LIB = os.path.join(os.path.dirname(ROOT), "library", "illus")
OUT = os.path.join(ROOT, "src", "paper", "illus.ts")


def read_svg(path: str) -> dict:
    s = open(path, encoding="utf-8").read()
    vb = re.search(r'viewBox="([^"]+)"', s)
    w, h = (float(x) for x in vb.group(1).split()[2:4]) if vb else (1000.0, 1000.0)
    sw = re.search(r'stroke-width="([\d.]+)"', s)
    paths = re.findall(r'<path d="([^"]+)"', s)
    return {"w": w, "h": h, "width": float(sw.group(1)) if sw else 12.0, "paths": paths}


def main() -> int:
    mf = os.path.join(LIB, "manifest.json")
    entries = json.load(open(mf, encoding="utf-8")) if os.path.exists(mf) else []
    out = {}
    for e in entries:
        svg = os.path.join(LIB, e["name"] + ".svg")
        if not os.path.exists(svg):
            print(f"no {svg}: skipped", file=sys.stderr)
            continue
        d = read_svg(svg)
        if not d["paths"]:
            print(f"{svg} has no strokes: skipped", file=sys.stderr)
            continue
        out[e["name"]] = {"about": e.get("about", ""), "tags": e.get("tags", []), "search": e.get("search", []), "svg": d}
    ts = (
        "// Traced illustrations for the art library: people and situations drawn in one hand, as pen strokes.\n"
        "// Generated by scripts/illus-import.py from library/illus/; do not edit by hand.\n"
        "import type {ArtDef} from './art';\n\n"
        "export const ILLUS: Record<string, ArtDef> = " + json.dumps({k: {"about": v["about"], "tags": v["tags"], "search": v["search"], "layers": [], "svg": v["svg"]} for k, v in out.items()}, ensure_ascii=False) + ";\n"
    )
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(ts)
    print(f"{len(out)} illustration(s) -> {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
